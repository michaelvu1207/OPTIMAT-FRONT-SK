#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from './node_modules/csv-parse/dist/esm/sync.js';
import {
  getArgValue,
  getDbLookupName,
  resolveCanonicalProviderName,
  shouldSkipProvider,
} from './provider-cleaning.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const DEFAULT_CSV_PATH = '/Users/maikyon/Downloads/OPTIMAT Provider Validation Updated Providers (3).csv';
const FUNCTIONS_BASE = 'https://htjohidcoyfuwfjecazu.functions.supabase.co';
const SUPABASE_ANON_KEY = process.env.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY || '';
const BACKUP_DIR = path.join(__dirname, 'backup');

const CSV_PATH = getArgValue(process.argv, '--csv') || DEFAULT_CSV_PATH;
const APPLY = process.argv.includes('--apply');
const ADMIN_URL =
  getArgValue(process.argv, '--admin-url') ||
  process.env.PROVIDER_ADVANCE_UPDATE_URL ||
  `${FUNCTIONS_BASE}/admin-provider-advance-update`;
const ADMIN_TOKEN = getArgValue(process.argv, '--admin-token') || process.env.PROVIDER_ADVANCE_UPDATE_TOKEN || '';

function parseMaybeJson(value) {
  if (typeof value !== 'string') return value ?? null;
  const trimmed = value.trim();
  if (!trimmed) return null;
  if (trimmed[0] !== '{' && trimmed[0] !== '[') return value;
  try {
    return JSON.parse(trimmed);
  } catch {
    return value;
  }
}

function normalizeLeadTime(rawValue) {
  const raw = String(rawValue || '').trim().replace(/\s+/g, ' ');
  if (!raw) return null;

  if (/^same day$/i.test(raw)) {
    return {
      type: 'real-time-book',
      advance_notice: 'same day',
      note: null,
    };
  }

  if (/^no booking required$/i.test(raw)) {
    return {
      type: 'real-time-book',
      advance_notice: 'no booking required',
      note: null,
    };
  }

  if (/^missing$/i.test(raw)) {
    return {
      type: 'in-advance-book',
      advance_notice: '7 days',
      note: 'CSV value was "Missing"; defaulted to 7 days per Contra Costa ADA standard.',
    };
  }

  return {
    type: 'in-advance-book',
    advance_notice: raw.replace(/^At least/i, 'at least'),
    note: null,
  };
}

function sqlJson(value) {
  return `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
}

function buildSql(updates) {
  const values = updates
    .map((update) => `  (${Number(update.provider_id)}, ${sqlJson(update.schedule_type)})`)
    .join(',\n');

  return `-- Generated by scripts/update-provider-advance-notice.mjs
-- Source: ${CSV_PATH}
-- Updates provider booking lead-time text only.

UPDATE optimat.providers AS p
SET
  schedule_type = v.schedule_type,
  updated_at = now()
FROM (
  VALUES
${values}
) AS v(provider_id, schedule_type)
WHERE p.provider_id = v.provider_id;
`;
}

async function fetchProviders() {
  const response = await fetch(`${FUNCTIONS_BASE}/providers`, {
    headers: {
      Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      apikey: SUPABASE_ANON_KEY,
      'Content-Type': 'application/json',
    },
  });

  if (!response.ok) {
    throw new Error(`GET /providers failed: ${response.status} ${await response.text()}`);
  }

  const payload = await response.json();
  if (!Array.isArray(payload?.data)) {
    throw new Error('GET /providers returned an unexpected payload shape');
  }

  return payload.data.map((provider) => ({
    ...provider,
    schedule_type: parseMaybeJson(provider.schedule_type),
  }));
}

function readCsvRows() {
  return parse(fs.readFileSync(CSV_PATH, 'utf8'), {
    bom: true,
    columns: true,
    relax_quotes: true,
    skip_empty_lines: true,
    trim: true,
  });
}

async function applyUpdates(updates) {
  if (!ADMIN_TOKEN) {
    throw new Error('Set PROVIDER_ADVANCE_UPDATE_TOKEN or pass --admin-token before using --apply.');
  }

  const response = await fetch(ADMIN_URL, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
      apikey: SUPABASE_ANON_KEY,
      'Content-Type': 'application/json',
      'x-admin-token': ADMIN_TOKEN,
    },
    body: JSON.stringify({ updates }),
  });

  const text = await response.text();
  const payload = text ? JSON.parse(text) : null;
  if (!response.ok) {
    throw new Error(`Admin update failed: ${response.status} ${text}`);
  }
  return payload;
}

async function main() {
  if (!SUPABASE_ANON_KEY) {
    throw new Error('Set VITE_SUPABASE_ANON_KEY or SUPABASE_ANON_KEY.');
  }
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const ts = new Date().toISOString().replace(/[:.]/g, '-');

  const providers = await fetchProviders();
  const byName = new Map(providers.map((provider) => [provider.provider_name, provider]));
  const rows = readCsvRows();

  const backupPath = path.join(BACKUP_DIR, `provider-advance-notice-backup-${ts}.json`);
  fs.writeFileSync(backupPath, JSON.stringify(providers, null, 2));

  const updates = [];
  const skipped = [];
  const missing = [];

  for (const row of rows) {
    const csvName = row['Provider Name']?.trim();
    if (!csvName || shouldSkipProvider(csvName)) continue;

    const normalized = normalizeLeadTime(row['Booking days in-advance']);
    if (!normalized) {
      skipped.push({ csvName, reason: 'blank Booking days in-advance' });
      continue;
    }

    const providerName = resolveCanonicalProviderName(csvName);
    const lookupName = getDbLookupName(csvName, providerName);
    const provider = byName.get(lookupName) || byName.get(providerName);

    if (!provider) {
      missing.push({ csvName, providerName, lookupName, advance_notice: normalized.advance_notice });
      continue;
    }

    const currentSchedule = provider.schedule_type && typeof provider.schedule_type === 'object'
      ? provider.schedule_type
      : {};
    const nextSchedule = {
      ...currentSchedule,
      type: normalized.type,
      advance_notice: normalized.advance_notice,
    };

    if (JSON.stringify(currentSchedule) === JSON.stringify(nextSchedule)) {
      skipped.push({ csvName, providerName: provider.provider_name, reason: 'already current' });
      continue;
    }

    updates.push({
      provider_id: Number(provider.provider_id),
      provider_name: provider.provider_name,
      csv_name: csvName,
      csv_value: row['Booking days in-advance']?.trim().replace(/\s+/g, ' '),
      schedule_type: nextSchedule,
      previous_schedule_type: currentSchedule,
      note: normalized.note,
    });
  }

  const payloadPath = path.join(BACKUP_DIR, `provider-advance-notice-updates-${ts}.json`);
  const latestPayloadPath = path.join(BACKUP_DIR, 'provider-advance-notice-updates-latest.json');
  const sqlPath = path.join(BACKUP_DIR, `provider-advance-notice-update-${ts}.sql`);
  const reportPath = path.join(BACKUP_DIR, `provider-advance-notice-report-${ts}.md`);

  fs.writeFileSync(payloadPath, JSON.stringify({ updates, missing, skipped }, null, 2));
  fs.writeFileSync(latestPayloadPath, JSON.stringify({ updates, missing, skipped }, null, 2));
  fs.writeFileSync(sqlPath, buildSql(updates));

  const reportLines = [
    '# Provider Advance Notice Update',
    '',
    `Source CSV: ${CSV_PATH}`,
    `Generated: ${new Date().toISOString()}`,
    '',
    `- Live providers fetched: ${providers.length}`,
    `- Updates prepared: ${updates.length}`,
    `- Blank/already-current rows skipped: ${skipped.length}`,
    `- Missing provider matches: ${missing.length}`,
    '',
    '## Updates',
    '',
    '| Provider ID | Provider | CSV value | New schedule_type | Note |',
    '|---:|---|---|---|---|',
    ...updates.map((update) =>
      `| ${update.provider_id} | ${update.provider_name.replaceAll('|', '\\|')} | ${String(update.csv_value).replaceAll('|', '\\|')} | \`${JSON.stringify(update.schedule_type).replaceAll('`', '\\`')}\` | ${update.note || ''} |`
    ),
  ];

  if (missing.length) {
    reportLines.push('', '## Missing Matches', '');
    for (const item of missing) {
      reportLines.push(`- ${item.csvName} -> ${item.providerName} (${item.advance_notice})`);
    }
  }

  fs.writeFileSync(reportPath, `${reportLines.join('\n')}\n`);

  console.log(`Backup: ${path.relative(process.cwd(), backupPath)}`);
  console.log(`Payload: ${path.relative(process.cwd(), payloadPath)}`);
  console.log(`SQL: ${path.relative(process.cwd(), sqlPath)}`);
  console.log(`Report: ${path.relative(process.cwd(), reportPath)}`);
  console.log(`Updates prepared: ${updates.length}`);
  console.log(`Missing matches: ${missing.length}`);

  for (const update of updates) {
    console.log(`${update.provider_id} ${update.provider_name}: ${JSON.stringify(update.previous_schedule_type)} -> ${JSON.stringify(update.schedule_type)}`);
  }

  if (!APPLY) {
    console.log('Dry run only. Re-run with --apply after deploying the secured admin updater.');
    return;
  }

  const result = await applyUpdates(updates);
  console.log(JSON.stringify(result, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
