#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const sourcePath = resolve('docs/migration/inventory/supabase-schema-raw.sql');
const outputPath = resolve('infra/migrations/0001_supabase_baseline.sql');
const modulePath = resolve('infra/lambda/migrator/baseline.ts');

let source = readFileSync(sourcePath, 'utf8');
source = source
  .replace(/^\\restrict .*$/gm, '')
  .replace(/^\\unrestrict .*$/gm, '')
  .replace('CREATE SCHEMA "optimat";', 'CREATE SCHEMA IF NOT EXISTS "optimat";')
  .replace('CREATE SCHEMA "public";', 'CREATE SCHEMA IF NOT EXISTS "public";');

const preamble = `-- Generated from docs/migration/inventory/supabase-schema-raw.sql.
-- Re-run scripts/migration/build-aurora-baseline.mjs after refreshing the live schema dump.
\nCREATE SCHEMA IF NOT EXISTS "public";
CREATE SCHEMA IF NOT EXISTS "extensions";
CREATE EXTENSION IF NOT EXISTS "pgcrypto" WITH SCHEMA "extensions";
CREATE EXTENSION IF NOT EXISTS "pg_trgm" WITH SCHEMA "extensions";
CREATE EXTENSION IF NOT EXISTS "postgis" WITH SCHEMA "extensions";
CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA "extensions";
\n`;

const postamble = `
-- AWS runtime access is mediated by the API, but the three source RLS-enabled
-- tables retain explicit database policies rather than silently losing RLS.
DROP POLICY IF EXISTS "optimat_app_full_access" ON "optimat"."providers";
CREATE POLICY "optimat_app_full_access" ON "optimat"."providers"
  FOR ALL TO "optimat_app" USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "optimat_app_full_access" ON "optimat"."chat_feedback";
CREATE POLICY "optimat_app_full_access" ON "optimat"."chat_feedback"
  FOR ALL TO "optimat_app" USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "optimat_app_full_access" ON "optimat"."chat_trip_state";
CREATE POLICY "optimat_app_full_access" ON "optimat"."chat_trip_state"
  FOR ALL TO "optimat_app" USING (true) WITH CHECK (true);

GRANT USAGE ON SCHEMA "optimat", "public", "extensions" TO "optimat_app";
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA "optimat" TO "optimat_app";
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA "public" TO "optimat_app";
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA "optimat", "public" TO "optimat_app";
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA "optimat", "public" TO "optimat_app";

ALTER DEFAULT PRIVILEGES IN SCHEMA "optimat"
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "optimat_app";
ALTER DEFAULT PRIVILEGES IN SCHEMA "optimat"
  GRANT USAGE, SELECT ON SEQUENCES TO "optimat_app";
ALTER DEFAULT PRIVILEGES IN SCHEMA "optimat"
  GRANT EXECUTE ON FUNCTIONS TO "optimat_app";

CREATE TABLE IF NOT EXISTS "optimat"."schema_migrations" (
  "version" text PRIMARY KEY,
  "applied_at" timestamptz NOT NULL DEFAULT now(),
  "source_checksum" text NOT NULL
);

INSERT INTO "optimat"."schema_migrations" ("version", "source_checksum")
VALUES ('0001_supabase_baseline', 'e0c2d18d6dcbc2c4f7593cdffba694b9724ad30f28f33357d2b0f03ee623c2cf')
ON CONFLICT ("version") DO NOTHING;
`;

const baseline = `${preamble}${source.trim()}\n${postamble}`;
mkdirSync(dirname(outputPath), { recursive: true });
mkdirSync(dirname(modulePath), { recursive: true });
writeFileSync(outputPath, baseline, { mode: 0o644 });
writeFileSync(
  modulePath,
  `// Generated by scripts/migration/build-aurora-baseline.mjs. Do not edit.\nexport const BASELINE_SQL = ${JSON.stringify(baseline)};\n`,
  { mode: 0o644 },
);
console.log(`Aurora baseline written to ${outputPath}`);
console.log(`Bundled migration module written to ${modulePath}`);
